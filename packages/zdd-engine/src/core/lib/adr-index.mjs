// ADR index extraction: number + title + first sentence +
// supersession stamps per ADR, mechanically extracted so the index is a
// generated artifact — rot-proof, never hand-edited, CI-checked like the
// other renderings. Extracted to lib so it is unit-testable (render.mjs
// runs render() on import, same reason as frontmatter.mjs).

// Stamp grammar (both shapes in the corpus): a line whose bold prefix is
// "Superseded [in part] by ADR-NNNN" or "... by [ADR-NNNN](...)", either as
// a top-of-file blockquote or an inline paragraph (ADR-0010's style).
const STAMP_RE = /\*\*Superseded( in part)? by \[?ADR-(\d{4})/g;

export function supersessionStamps(body) {
  const out = [];
  for (const m of body.matchAll(STAMP_RE)) {
    out.push({ partial: Boolean(m[1]), by: m[2] });
  }
  return out;
}

// First sentence of the first prose paragraph — skipping the # title,
// blockquote stamp lines, and blank lines. ADR bodies are hard-wrapped at
// ~80 cols, so the paragraph's lines are joined before sentence-splitting
// (line-by-line extraction shipped mid-clause fragments — review
// finding). Capped so a runaway first sentence can't bloat the index (same
// instinct as the agent index's brief()).
export function firstSentence(body) {
  const paragraph = [];
  for (const rawLine of body.split("\n")) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#") || line.startsWith(">")) {
      if (paragraph.length) break; // paragraph ended
      continue; // still skipping preamble
    }
    paragraph.push(line);
  }
  if (!paragraph.length) return "";
  let s = paragraph.join(" ").split(/(?<=\.)\s/)[0].trim();
  if (s.length > 200) s = s.slice(0, cutBeforeLink(s, 199)).trimEnd() + "…";
  return s;
}

// The cap must never land inside a markdown link: a cut "[ADR-0016](0016-pu…"
// is a broken link in the index, and one rebaseAdrLinks below cannot see
// (ADR_HREF_RE wants the closing ".md"). When position `at` falls within a
// "[text](target)" span, back the cut off to the "[" so the link is dropped
// whole (1.3.1). Links are matched left to right from the sentence start;
// unbalanced brackets are left as plain text, matching the cap's old shape.
const LINK_RE = /\[[^\]]*\]\([^)]*\)/g;

function cutBeforeLink(s, at) {
  for (const m of s.matchAll(LINK_RE)) {
    const start = m.index;
    const end = start + m[0].length;
    if (start >= at) break;
    if (end > at) return start;
  }
  return at;
}

// An ADR body's own links to sibling ADRs are relative to the ADR dir — e.g.
// "[ADR-0043](0043-foo.md)" — but the index they get embedded into lives one
// level up at zdd/adr-index.md, where that href resolves to zdd/0043-foo.md
// and 404s. Supersession sentences are the common case (they open with a link
// to the ADR they supersede), so most stamped ADRs carried a broken link into
// the index. Rebase bare NNNN-*.md targets onto adr/; leave anything already
// qualified, absolute, or anchored alone. Found by a review lane.
const ADR_HREF_RE = /\]\((\d{4}-[^)/#]+\.md)/g;

export function rebaseAdrLinks(text) {
  return text.replace(ADR_HREF_RE, "](adr/$1");
}

// One line per ADR, numerically sorted. Hrefs are relative to zdd/ (the
// index lives at zdd/adr-index.md) so they resolve on GitHub, matching the
// agent index's convention — including the links carried inside an extracted
// first sentence, which is what rebaseAdrLinks above is for.
//
// `sets` (decision 0033) is given only when the harness set is configured,
// one index per set: { title, shared (the line saying the numbers are
// shared), href(adr), rebase(text, adr), stampOf(num) — how a superseding
// ADR is named, marked and linked when it is in the other set }. Without it
// the bytes are the one-set index's, unchanged.
export function buildAdrIndex(adrs, sets) {
  const lines = [];
  lines.push(sets ? sets.title : "# ADR index");
  lines.push("");
  lines.push(
    "One line per ADR: number — title — first sentence, plus supersession stamps.",
    "Generated by `npx -y @rich-rees/zdd@<release> render` from the ADR corpus — do not edit.",
    "Read this whole at orientation; drill into full ADR bodies only when cited",
    "(by the task, the spec, the glossary, or the agent index) — and declare the",
    "selection.",
  );
  if (sets) lines.push(sets.shared);
  lines.push("");
  const sorted = [...adrs].sort((a, b) => (a.num < b.num ? -1 : 1));
  const stampName = sets ? sets.stampOf : (num) => `ADR-${num}`;
  for (const adr of sorted) {
    const sentence = sets ? sets.rebase(firstSentence(adr.body), adr) : rebaseAdrLinks(firstSentence(adr.body));
    const stamps = supersessionStamps(adr.body);
    let line = `- [ADR-${adr.num}](${sets ? sets.href(adr) : `adr/${adr.file}`}) — ${adr.title}`;
    if (sentence) line += ` — ${sentence}`;
    const partial = stamps.filter((s) => s.partial).map((s) => stampName(s.by));
    const full = stamps.filter((s) => !s.partial).map((s) => stampName(s.by));
    if (full.length) line += ` _(superseded by ${full.join(", ")})_`;
    if (partial.length) line += ` _(superseded in part by ${partial.join(", ")})_`;
    lines.push(line);
  }
  lines.push("");
  return lines.join("\n");
}
