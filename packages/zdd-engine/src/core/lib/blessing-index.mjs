// Blessing index (2.0.0; where and why since ZDD-1, decision 0031): one line
// per blessing in the blessing store, so a session choosing patterns reads
// every trigger question at once and opens only the blessings that match its
// work. Generated like the ADR index — mechanically extracted, never
// hand-edited, checked by `render --check` — and in lib so it is
// unit-testable (render.mjs runs render() on import).
//
// House rules first: a blessing with `applies-to` is listed under its app or
// package, and every one is read in full for an app the work touches. Then
// every other blessing in one list; each section high first, then by
// question (decision 0045). Each line carries two
// pointers, where (the exemplar, and for an `extend` blessing who uses it)
// and why (the ADRs it cites, else its "because …" clause). A blessing with
// no question is still listed, flagged, so nothing in the store is invisible
// here even before lint fails it. A blessing marked `importance: high`
// (decision 0045) comes first in its own section, its line opening with a
// bold **high**, so the house-rule sections stay whole. Measured on a real map: ~95 tokens per
// blessing in full against ~25 per line here, which keeps the index loadable
// whole at hundreds of blessings.

const OPENING_MAX = 80;
const USERS_SHOWN = 5;

const printable = (t) => String(t).replace(/[\x00-\x1f\x7f]/g, "?");
// Link text with its brackets and backslashes escaped; a destination with a
// space, a bracket or an angle bracket in angle brackets, `<` and `>`
// percent-encoded; a code span opened with more backticks than it holds
// (CR-023).
const label = (t) => printable(t).replace(/([\\\[\]])/g, "\\$1");
const dest = (d) => (/[\s()<>]/.test(d) ? `<${printable(d).replace(/</g, "%3C").replace(/>/g, "%3E")}>` : printable(d));
const code = (t) => {
  const s = printable(t);
  const run = Math.max(0, ...[...s.matchAll(/`+/g)].map((m) => m[0].length));
  const fence = "`".repeat(run + 1);
  return run ? `${fence} ${s} ${fence}` : `\`${s}\``;
};
const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
// High first (decision 0045), then by trigger question, then id — the one
// order of the index and of the viewer's list.
const highFirst = (a, b) => (b.importance === "high") - (a.importance === "high");
const question = (b) => b.shape.question ?? "";
const storeOrder = (a, b) => highFirst(a, b) || byText(question(a), question(b)) || byText(a.id, b.id);

// `blessings`: the store as lib/blessings.mjs reads it.
// `opts.adrHref(num)`: index-relative href of an ADR, or null if it does not
//   exist (the citation is then printed bare; lint reports it).
// `opts.blessingHref(id)`: index-relative href of a blessing file.
// `opts.mapPage(id)`: { title, href } for a semantic-map page by its path
//   under the map folder, or null.
// `opts.usersOf(blessing)`: the records using an `extend` blessing's
//   exemplar, or null when ZDD does not know them.
// `opts.unknownWhy(blessing)`: why the users are unknown, in words, or null.
// Returns the index text and the number of blessings in it.
export function buildBlessingIndex(blessings, opts) {
  const lines = [];
  lines.push("# Blessing index", "");
  lines.push(
    "One line per blessing: its trigger question, where the code is, and why.",
    "Generated by `npx -y @rich-rees/zdd render` from the blessing store — do not edit.",
    "Read this whole when choosing patterns, and open a blessing in full only when",
    "its question matches the work. A house rule for an app is listed under that",
    "app: for an app the work touches, read every one of them in full. An `extend`",
    "blessing names who uses the code: extending it means retesting them. A line",
    "that opens with **high** is a blessing not to reinvent: follow it, or say in",
    "the pattern plan why not.",
    "",
  );
  if (!blessings.length) {
    lines.push("No blessings yet. A blessing names the exemplar to copy or extend and the", "pattern to refuse, one file per blessing in the blessing store; `update` mints them.", "");
    return { text: lines.join("\n"), count: 0 };
  }
  const ordered = [...blessings].sort(storeOrder);
  const houseRules = new Map();
  const rest = [];
  for (const b of ordered) {
    if (b.appliesTo) {
      if (!houseRules.has(b.appliesTo)) houseRules.set(b.appliesTo, []);
      houseRules.get(b.appliesTo).push(b);
    } else rest.push(b);
  }
  const groups = [...houseRules].map(([id, list]) => ({ id, page: opts.mapPage(id), list }));
  groups.sort((a, b) => byText(a.page?.title ?? a.id, b.page?.title ?? b.id) || byText(a.id, b.id));
  for (const g of groups) {
    lines.push(g.page ? `## Applies to [${label(g.page.title)}](${dest(g.page.href)})` : `## Applies to ${printable(g.id)} _(no such map page)_`, "");
    for (const b of g.list) lines.push(`- ${line(b, opts)}`);
    lines.push("");
  }
  if (rest.length) {
    lines.push(groups.length ? "## Every other blessing" : "## Blessings", "");
    for (const b of rest) lines.push(`- ${line(b, opts)}`);
    lines.push("");
  }
  return { text: lines.join("\n"), count: blessings.length };
}

function line(b, opts) {
  const shape = b.shape;
  const head = shape.question
    ? `[${label(shape.question)}](${dest(opts.blessingHref(b.id))})`
    : `[_(no trigger question)_](${dest(opts.blessingHref(b.id))}) ${printable(shape.visible.length > OPENING_MAX ? shape.visible.slice(0, OPENING_MAX - 1).trimEnd() + "…" : shape.visible)}`;
  const kind = b.kind === "copy" || b.kind === "extend" ? b.kind : "where";
  let where = b.where ? `${code(b.where.path)}${b.where.symbol ? ` (${printable(b.where.symbol)})` : ""}` : "_none given_";
  if (b.kind === "extend" && b.where) {
    const users = opts.usersOf(b);
    if (users === null) where += `, users unknown to ZDD${opts.unknownWhy?.(b) ? ` (${printable(opts.unknownWhy(b))})` : ""}`;
    else if (!users.length) where += ", used by nothing ZDD sees";
    else {
      const names = users.slice(0, USERS_SHOWN).map((u) => printable(u.title ?? u.id));
      where += `, used by ${users.length}: ${names.join(", ")}${users.length > USERS_SHOWN ? `, +${users.length - USERS_SHOWN} more` : ""}`;
    }
  }
  let why;
  if (b.adrs.length) why = b.adrs.map((n) => (opts.adrHref(n) ? `[ADR-${n}](${opts.adrHref(n)})` : `ADR-${n}`)).join(", ");
  else if (shape.because) why = printable(shape.because);
  else why = "_no reason given_";
  return `${b.importance === "high" ? "**high** " : ""}${head} — ${kind}: ${where} · why: ${why}`;
}

// The blessing store as a viewer embeds it (ZDD-2, decision 0043): the
// same facts as an index line, read once here so the viewer never parses
// the store, high first and then by question, then id (decision 0045), and
// with the index's cap on users. `importance` is "high" or null (normal). A missing fact is null, never guessed; `usedBy` is only on an
// `extend` blessing with a `where` (null: unknown to ZDD).
// `blessings`: the store as lib/blessings.mjs reads it (with `file`).
// `opts.mapPage(id)`: { node, title } for a semantic-map page by its path
//   under the map folder, or null.
// `opts.usersOf(blessing)`: [{ node, title }] (node: a graph node id, or
//   null) using an `extend` blessing's exemplar, or null.
export function viewerBlessings(blessings, opts) {
  const page = (id) => {
    if (!id) return null;
    const p = opts.mapPage(id);
    return { path: id, node: p ? p.node : null, title: p ? p.title : null };
  };
  return [...blessings]
    .sort(storeOrder)
    .map((b) => {
      const visible = b.shape.visible;
      const out = {
        id: b.id,
        file: b.file ?? null,
        question: b.shape.question,
        opening: b.shape.question ? null : visible.length > OPENING_MAX ? visible.slice(0, OPENING_MAX - 1).trimEnd() + "…" : visible,
        kind: b.kind,
        importance: b.importance === "high" ? "high" : null,
        where: b.where,
        appliesTo: page(b.appliesTo),
        firstBuiltIn: page(b.firstBuiltIn),
        adrs: b.adrs,
        body: b.body ?? "",
      };
      if (b.kind === "extend" && b.where) {
        const users = opts.usersOf(b);
        out.usedBy = users === null ? null : { count: users.length, shown: users.slice(0, USERS_SHOWN).map((u) => ({ node: u.node ?? null, title: u.title })) };
      }
      return out;
    });
}
